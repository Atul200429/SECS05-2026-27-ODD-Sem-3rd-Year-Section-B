"""**3. Perform basic data preprocessing by handling missing values, encoding categorical variables (if any), and selecting relevant features.**"""

# 1. Check for missing values
print("Missing values in each column:")
print(df.isnull().sum())

# Fill missing numerical values with median
numerical_columns = ['Area', 'Bedrooms', 'Bathrooms', 'Floors', 'YearBuilt']

for column in numerical_columns:
    df[column] = df[column].fillna(df[column].median())

# Fill missing categorical values with mode
categorical_columns = ['Location', 'Condition', 'Garage']

for column in categorical_columns:
    df[column] = df[column].fillna(df[column].mode()[0])

print("\nMissing values after handling:")
print(df.isnull().sum())


# 2. Select relevant features
X = df[['Area', 'Bedrooms', 'Bathrooms', 'Floors',
        'YearBuilt', 'Location', 'Condition', 'Garage']]

# Target variable
y = df['Price']

print("\nSelected Features:")
print(X.columns.tolist())

print("\nTarget Variable:")
print("Price")


# 3. Encode categorical variables
X = pd.get_dummies(
    X,
    columns=['Location', 'Condition', 'Garage'],
    drop_first=True
)

print("\nData after encoding categorical variables:")
display(X.head())

print("\nShape of processed data:", X.shape)

"""**4. Split the dataset into training and testing sets using an appropriate train-test ratio (e.g., 80:20).**

"""

# Splitting dataset into training and testing sets
