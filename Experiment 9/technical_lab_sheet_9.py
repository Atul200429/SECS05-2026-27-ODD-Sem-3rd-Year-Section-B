import pandas as pd
import numpy as np
import matplotlib.pyplot as plt
import seaborn as sns
import plotly.express as px

sns.set_theme(style="whitegrid")

# Load the uploaded dataset
df = pd.read_csv("Global Superstore.csv", encoding="latin1")

print("Dataset loaded successfully!")
print("Dataset Shape:", df.shape)

print("\nFirst 5 Rows:")
display(df.head())

print("\nColumn Names:")
print(df.columns.tolist())

# Check dataset information
print("Dataset Information:")
df.info()

print("\nMissing Values in Each Column:")
print(df.isnull().sum())

print("\nTotal Missing Values:", df.isnull().sum().sum())

print("\nTotal Duplicate Rows:", df.duplicated().sum())

# Create a working copy of the dataset
df_clean = df.copy()

# Remove exact duplicate rows
df_clean = df_clean.drop_duplicates().copy()

# Remove rows missing essential analysis values
df_clean = df_clean.dropna(
    subset=["Sales", "Profit", "Quantity", "Category", "Region"]
).copy()

# Convert numerical columns to numeric format
numeric_columns = [
    "Sales", "Profit", "Quantity", "Discount", "Shipping Cost"
]

for col in numeric_columns:
    df_clean[col] = pd.to_numeric(df_clean[col], errors="coerce")

# Remove rows where essential numeric values are invalid
df_clean = df_clean.dropna(
    subset=["Sales", "Profit", "Quantity"]
).copy()

print("Original Dataset Shape:", df.shape)
print("Cleaned Dataset Shape:", df_clean.shape)
print("Missing Values Remaining in Essential Columns:")
print(df_clean[["Sales", "Profit", "Quantity"]].isnull().sum())

# Generate descriptive statistics
print("Statistical Summary:")
display(df_clean.describe())

print("\nUnique Product Categories:")
print(df_clean["Category"].nunique())

print("\nUnique Regions:")
print(df_clean["Region"].nunique())

print("\nUnique Countries:")
print(df_clean["Country"].nunique())

print("\nUnique Customers:")
print(df_clean["Customer ID"].nunique())

print("\nUnique Orders:")
print(df_clean["Order ID"].nunique())

# Overall sales and profit analysis
total_sales = df_clean["Sales"].sum()
total_profit = df_clean["Profit"].sum()
total_quantity = df_clean["Quantity"].sum()
total_orders = df_clean["Order ID"].nunique()
total_customers = df_clean["Customer ID"].nunique()

profit_margin = (
    (total_profit / total_sales) * 100
    if total_sales != 0 else 0
)

print("========== BUSINESS OVERVIEW ==========")
print(f"Total Sales: {total_sales:,.2f}")
print(f"Total Profit: {total_profit:,.2f}")
print(f"Total Quantity Sold: {total_quantity:,}")
print(f"Total Unique Orders: {total_orders:,}")
print(f"Total Unique Customers: {total_customers:,}")
print(f"Overall Profit Margin: {profit_margin:.2f}%")

# Category-wise analysis
category_analysis = (
    df_clean.groupby("Category", as_index=False)
    .agg(
        Total_Sales=("Sales", "sum"),
        Total_Profit=("Profit", "sum"),
        Total_Quantity=("Quantity", "sum")
    )
    .sort_values("Total_Sales", ascending=False)
)

print("Category-wise Business Performance:")
display(category_analysis)

# Region-wise analysis
region_analysis = (
    df_clean.groupby("Region", as_index=False)
    .agg(
        Total_Sales=("Sales", "sum"),
        Total_Profit=("Profit", "sum"),
        Total_Quantity=("Quantity", "sum")
    )
    .sort_values("Total_Profit", ascending=False)
)

print("\nRegion-wise Business Performance:")
display(region_analysis)

# Sub-category analysis
subcategory_analysis = (
    df_clean.groupby("Sub-Category", as_index=False)
    .agg(
        Total_Sales=("Sales", "sum"),
        Total_Profit=("Profit", "sum"),
        Total_Quantity=("Quantity", "sum")
    )
    .sort_values("Total_Profit", ascending=True)
)

print("Five Lowest-Profit Sub-Categories:")
display(subcategory_analysis.head(5))

print("\nFive Highest-Profit Sub-Categories:")
display(subcategory_analysis.tail(5).sort_values(
    "Total_Profit", ascending=False
))

