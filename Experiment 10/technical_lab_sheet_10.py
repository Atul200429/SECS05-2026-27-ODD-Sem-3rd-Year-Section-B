from scipy.stats import f_oneway

# Prepare price groups for each location
location_groups = [
    group["Price"].values
    for _, group in df_clean.groupby("Location")
    if len(group) >= 2
]

print("Number of Location Groups:", len(location_groups))

if len(location_groups) >= 2:
    f_statistic, anova_p_value = f_oneway(*location_groups)

    print("ANOVA F-statistic:", round(f_statistic, 4))
    print("ANOVA P-value:", anova_p_value)

    if anova_p_value < 0.05:
        print("Decision: Reject the null hypothesis.")
        print("Conclusion: At least one location has a significantly different mean price.")
    else:
        print("Decision: Fail to reject the null hypothesis.")
        print("Conclusion: No statistically significant difference was detected.")
else:
    print("ANOVA could not be performed because fewer than two valid groups exist.")

