"""**2. Import the required Python libraries and load the dataset into a Pandas DataFrame.**"""

import pandas as pd
import numpy as np
import matplotlib.pyplot as plt
import seaborn as sns

# Load the dataset
df = pd.read_csv("Online Retail Dataset.csv", encoding="latin1")

# Display confirmation message
print("Dataset loaded successfully!")

# Display the shape of the dataset
print("Shape of dataset:", df.shape)

# Display the first five rows
print("\nFirst five rows of the dataset:")
print(df.head())

"""**3. Perform data preprocessing by handling missing values, removing duplicates, and selecting relevant features such as Age, Annual Income, and Spending Score.**"""

# Display missing values before preprocessing
print("Missing values before preprocessing:")
print(df.isnull().sum())

# Remove rows with missing CustomerID
df = df.dropna(subset=["CustomerID"])

# Remove duplicate rows
df = df.drop_duplicates()

# Convert InvoiceDate to datetime format
df["InvoiceDate"] = pd.to_datetime(df["InvoiceDate"])

# Remove cancelled transactions
df = df[~df["InvoiceNo"].astype(str).str.startswith("C")]

# Remove invalid transactions
df = df[df["Quantity"] > 0]
df = df[df["UnitPrice"] > 0]

# Select relevant features for customer segmentation
selected_features = df[
    ["CustomerID", "InvoiceDate", "InvoiceNo", "Quantity", "UnitPrice"]
]

# Display preprocessing results
print("\nData preprocessing completed successfully!")

print("\nShape after preprocessing:", df.shape)

print("\nSelected Features:")
print(selected_features.head())

"""**4. Normalize or standardize the selected features to ensure that all variables contribute equally during clustering.**"""

# Calculate total purchase amount
df["TotalAmount"] = df["Quantity"] * df["UnitPrice"]

# Create customer-level RFM features
reference_date = df["InvoiceDate"].max() + pd.Timedelta(days=1)

rfm = df.groupby("CustomerID").agg({
    "InvoiceDate": lambda x: (reference_date - x.max()).days,
    "InvoiceNo": "nunique",
    "TotalAmount": "sum"
})

rfm.columns = ["Recency", "Frequency", "Monetary"]

# Select features for clustering
features = rfm[["Recency", "Frequency", "Monetary"]]

# Standardize the features
from sklearn.preprocessing import StandardScaler

scaler = StandardScaler()
scaled_features = scaler.fit_transform(features)

print("Selected features standardized successfully!")
print(scaled_features[:5])

"""**5. Determine the optimal number of clusters using the Elbow Method and validate the result using the Silhouette Score.**"""

# Determining Optimal Number of Clusters
from sklearn.cluster import KMeans
from sklearn.metrics import silhouette_score

# Elbow Method
inertia = []

for k in range(2, 11):
    kmeans = KMeans(n_clusters=k, random_state=42, n_init=10)
    kmeans.fit(scaled_features)
    inertia.append(kmeans.inertia_)

# Plot Elbow Curve
plt.figure(figsize=(6, 3))
plt.plot(range(2, 11), inertia, marker="o")
plt.xlabel("Number of Clusters (K)")
plt.ylabel("Inertia")
plt.title("Elbow Method")
plt.xticks(range(2, 11))
plt.grid(True)
plt.show()

# Silhouette Score
silhouette_scores = []

for k in range(2, 11):
    kmeans = KMeans(n_clusters=k, random_state=42, n_init=10)
    labels = kmeans.fit_predict(scaled_features)
    score = silhouette_score(scaled_features, labels)
    silhouette_scores.append(score)

# Display Silhouette Scores
for k, score in zip(range(2, 11), silhouette_scores):
    print("K =", k, "Silhouette Score =", round(score, 4))

# Find the K with the highest Silhouette Score
best_k = range(2, 11)[np.argmax(silhouette_scores)]

print("\nOptimal Number of Clusters:", best_k)
print("Highest Silhouette Score:", round(max(silhouette_scores), 4))

"""**6. Apply the K-Means Clustering algorithm with the selected value of K to group customers into distinct clusters.**"""

# Apply K-Means using the selected optimal K
kmeans = KMeans(
    n_clusters=best_k,
    random_state=42,
    n_init=10
)

# Assign clusters to customers
rfm["Cluster"] = kmeans.fit_predict(scaled_features)

print("K-Means clustering applied successfully!")
print("Number of clusters:", best_k)

# Display the first few customers with their cluster
print("\nCustomer clusters:")
print(rfm.head())

# Display number of customers in each cluster
print("\nNumber of customers in each cluster:")
print(rfm["Cluster"].value_counts().sort_index())

"""**7. Visualize the clusters using scatter plots and highlight the cluster centroids for better interpretation.**"""

# Calculate cluster centroids
centroids = kmeans.cluster_centers_

# Create scatter plot
plt.figure(figsize=(6, 4))

sns.scatterplot(
    x=scaled_features[:, 0],
    y=scaled_features[:, 2],
    hue=rfm["Cluster"],
    palette="Set1",
    s=60
)

# Highlight cluster centroids
plt.scatter(
    centroids[:, 0],
    centroids[:, 2],
    marker="X",
    s=250,
    c="black",
    label="Centroids"
)

plt.xlabel("Recency (Standardized)")
plt.ylabel("Monetary (Standardized)")
plt.title("Customer Clusters with Centroids")
plt.legend(title="Cluster")

plt.show()

